import type { Conclusion, PullRequest, Workflow, WorkflowRun } from '../domain/types';

/**
 * Sample fleet used until GITHUB_TOKEN is set.
 *
 * The run timestamps are real offsets from now, so the triage logic in
 * triage.ts genuinely classifies this data rather than reading canned labels —
 * the sample exercises the same code path the live data will.
 */

const MINUTE = 60_000;
const HOUR = 3_600_000;
const DAY = 86_400_000;

let nextId = 1000;

function mkRuns(
  codes: Conclusion[],
  stepMs: number,
  firstOffsetMs: number,
  event = 'push',
): WorkflowRun[] {
  const now = Date.now();
  return codes.map((conclusion, i) => ({
    id: nextId++,
    conclusion,
    createdAt: new Date(now - firstOffsetMs - i * stepMs).toISOString(),
    durationMs: conclusion === 'running' ? null : 90_000 + ((i * 37_000) % 400_000),
    headSha: Math.random().toString(16).slice(2, 42).padEnd(40, '0'),
    event,
    htmlUrl: '#',
  }));
}

const repeat = (c: Conclusion, n: number): Conclusion[] => Array.from({ length: n }, () => c);
const S: Conclusion = 'success';
const F: Conclusion = 'failure';

